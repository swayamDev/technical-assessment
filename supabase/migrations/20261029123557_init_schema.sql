-- Rent collection schema: tables, constraints and integrity triggers.
-- Access control (grants, RLS, storage) lives in the next migration.

create extension if not exists btree_gist with schema extensions;

-- Helpers and trigger functions live outside the API-exposed schemas.
create schema private;

-- ---------------------------------------------------------------------------
-- Organizations and people
-- ---------------------------------------------------------------------------

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  created_at timestamptz not null default now()
);

-- A staff member or manager belongs to exactly one organization: user_id is the key.
create table public.memberships (
  -- No FK to auth.users: Prisma cannot introspect cross-schema references without
  -- modelling the whole auth schema. A dangling user_id can never sign in.
  user_id uuid primary key,
  org_id uuid not null references public.organizations (id),
  role text not null check (role in ('manager', 'staff')),
  created_at timestamptz not null default now()
);
create index memberships_org_id_idx on public.memberships (org_id);

create table public.units (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  name text not null check (length(trim(name)) > 0),
  created_at timestamptz not null default now(),
  unique (org_id, name),
  unique (id, org_id)
);

create table public.tenants (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  user_id uuid unique, -- auth.users id; see memberships.user_id
  full_name text not null check (length(trim(full_name)) > 0),
  email text not null,
  phone text check (phone ~ '^\+?[0-9][0-9 -]{5,19}$'),
  created_at timestamptz not null default now(),
  unique (id, org_id)
);
create index tenants_org_id_idx on public.tenants (org_id);

-- ---------------------------------------------------------------------------
-- Leases and invoices
-- ---------------------------------------------------------------------------

create table public.leases (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  unit_id uuid not null,
  tenant_id uuid not null,
  start_date date not null,
  end_date date not null,
  monthly_rent_sen bigint not null check (monthly_rent_sen > 0),
  deposit_sen bigint not null check (deposit_sen >= 0),
  created_by uuid,
  created_at timestamptz not null default now(),
  check (end_date >= start_date),
  -- The unit and the tenant must belong to the lease's organization.
  foreign key (unit_id, org_id) references public.units (id, org_id),
  foreign key (tenant_id, org_id) references public.tenants (id, org_id),
  -- Leases on the same unit never overlap (both dates inclusive), even under concurrency.
  constraint leases_no_overlap exclude using gist (
    unit_id with =,
    daterange(start_date, end_date, '[]') with &&
  ),
  unique (id, org_id)
);
create index leases_org_id_idx on public.leases (org_id);
create index leases_tenant_id_idx on public.leases (tenant_id);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  lease_id uuid not null,
  kind text not null check (kind in ('deposit', 'rent')),
  period_index integer,
  period_start date,
  period_end date,
  due_date date not null,
  amount_sen bigint not null check (amount_sen >= 0),
  created_at timestamptz not null default now(),
  check (
    (kind = 'deposit' and period_index is null and period_start is null and period_end is null)
    or (kind = 'rent' and period_index >= 0 and period_start is not null and period_end >= period_start)
  ),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  unique nulls not distinct (lease_id, kind, period_index),
  unique (id, lease_id, org_id)
);
create index invoices_org_id_idx on public.invoices (org_id);

-- ---------------------------------------------------------------------------
-- Payments
-- ---------------------------------------------------------------------------

create table public.gateway_bills (
  -- Random, unguessable id generated by the app (bill_ + 128 random bits).
  id text primary key check (id ~ '^bill_[0-9a-f]{32}$'),
  org_id uuid not null,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed')),
  transaction_id text,
  paid_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  unique (id, lease_id, org_id)
);
create index gateway_bills_lease_id_idx on public.gateway_bills (lease_id);
create index gateway_bills_org_id_idx on public.gateway_bills (org_id);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  unapplied_sen bigint not null default 0 check (unapplied_sen >= 0 and unapplied_sen <= amount_sen),
  method text not null check (method in ('cash', 'bank_transfer', 'online')),
  status text not null check (status in ('pending_verification', 'approved', 'rejected', 'voided')),
  received_at timestamptz not null,
  slip_path text unique,
  gateway_bill_id text unique, -- at most one payment per bill, ever
  recorded_by uuid,
  approved_by uuid,
  approved_at timestamptz,
  rejected_by uuid,
  rejected_at timestamptz,
  rejection_reason text,
  voided_by uuid,
  voided_at timestamptz,
  void_reason text,
  created_at timestamptz not null default now(),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  foreign key (gateway_bill_id, lease_id, org_id) references public.gateway_bills (id, lease_id, org_id),
  -- A bank transfer always has a slip, and only bank transfers do.
  check ((method = 'bank_transfer') = (slip_path is not null)),
  -- Online payments always come from a bill, and only online payments do.
  check ((method = 'online') = (gateway_bill_id is not null)),
  -- A slip lives in its own organization's folder of the payment-slips bucket.
  check (slip_path is null or (slip_path like org_id::text || '/%' and slip_path not like '%..%')),
  check (status <> 'rejected' or length(trim(rejection_reason)) >= 5),
  check (status <> 'voided' or length(trim(void_reason)) >= 5),
  check (method <> 'online' or status <> 'pending_verification'),
  unique (id, lease_id, org_id)
);
create index payments_lease_id_idx on public.payments (lease_id);
create index payments_org_received_idx on public.payments (org_id, received_at) where status = 'approved';

create table public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  lease_id uuid not null,
  payment_id uuid not null,
  invoice_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  created_at timestamptz not null default now(),
  -- Payment and invoice must belong to the same lease and organization.
  foreign key (payment_id, lease_id, org_id) references public.payments (id, lease_id, org_id),
  foreign key (invoice_id, lease_id, org_id) references public.invoices (id, lease_id, org_id),
  unique (payment_id, invoice_id)
);
create index payment_allocations_invoice_id_idx on public.payment_allocations (invoice_id);
create index payment_allocations_lease_id_idx on public.payment_allocations (lease_id);

-- A bank transfer's slip must be an existing file in the payment-slips bucket.
create function private.check_payment_slip() returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.slip_path is not null and not exists (
    select 1 from storage.objects o where o.bucket_id = 'payment-slips' and o.name = new.slip_path
  ) then
    raise exception 'slip_path does not point to an uploaded slip' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger payments_check_slip
before insert or update of slip_path on public.payments
for each row execute function private.check_payment_slip();

-- ---------------------------------------------------------------------------
-- Audit log: append-only for every role, including the owner and service role
-- ---------------------------------------------------------------------------

create table public.audit_log (
  id bigint generated always as identity primary key,
  org_id uuid not null references public.organizations (id),
  actor_id uuid, -- null when the gateway (system) acted
  action text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_log_org_created_idx on public.audit_log (org_id, created_at desc);

create function private.audit_log_append_only() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'audit_log is append-only' using errcode = 'P0001';
end;
$$;

create trigger audit_log_no_update_delete
before update or delete on public.audit_log
for each row execute function private.audit_log_append_only();

create trigger audit_log_no_truncate
before truncate on public.audit_log
for each statement execute function private.audit_log_append_only();
